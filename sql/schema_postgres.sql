-- PostgreSQL schema used when DATABASE_URL points to Neon or Render PostgreSQL.
CREATE TABLE IF NOT EXISTS owners (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    phone VARCHAR(40) NOT NULL,
    email VARCHAR(254),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS plots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plot_number VARCHAR(40) NOT NULL UNIQUE,
    area_sqm DOUBLE PRECISION NOT NULL CHECK (area_sqm > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('free', 'occupied', 'leased', 'disputed')),
    owner_id INTEGER REFERENCES owners(id) ON DELETE SET NULL,
    debt DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (debt >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
    amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
    payment_date DATE NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_plots_owner_id ON plots(owner_id);
CREATE INDEX IF NOT EXISTS idx_payments_owner_date ON payments(owner_id, payment_date);
